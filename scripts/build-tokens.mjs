import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const source = JSON.parse(fs.readFileSync(path.join(root, 'tokens/kaui.tokens.json'), 'utf8'));
const out = path.join(root, 'dist/tokens');
fs.mkdirSync(out, { recursive: true });
const hex = (v) => v.replace('#', '').toUpperCase();
const color = (v, kind) => kind === 'swift'
  ? `Color(red: ${parseInt(hex(v).slice(0, 2), 16)}/255.0, green: ${parseInt(hex(v).slice(2, 4), 16)}/255.0, blue: ${parseInt(hex(v).slice(4, 6), 16)}/255.0)`
  : `Color(0xFF${hex(v)})`;
const px = (v) => v === '0' ? '0' : String(parseFloat(v) * 16);
const flatColors = [];
for (const [family, palette] of Object.entries(source.colors)) {
  if (typeof palette === 'object') for (const [shade, value] of Object.entries(palette)) flatColors.push([`${family}${shade[0].toUpperCase()}${shade.slice(1)}`, value]);
  else flatColors.push([family, palette]);
}

fs.writeFileSync(path.join(out, 'kaui.tokens.json'), JSON.stringify({ ...source, generatedAt: new Date().toISOString() }, null, 2) + '\n');
const css = [':root {'];
flatColors.forEach(([name, value]) => css.push(`  --k-color-${name.replace(/([A-Z])/g, '-$1').toLowerCase()}: ${value};`));
Object.entries(source.spacing).forEach(([k, v]) => css.push(`  --k-spacing-${k}: ${v};`));
Object.entries(source.radius).forEach(([k, v]) => css.push(`  --k-radius-${k}: ${v};`));
Object.entries(source.typography.size).forEach(([k, v]) => css.push(`  --k-size-${k}: ${v};`));
css.push('}', '');
fs.writeFileSync(path.join(out, 'kaui.tokens.css'), css.join('\n'));

const dart = ['// Generated by KAUI Token Builder.', "import 'package:flutter/widgets.dart';", '', 'class KauiColors {'];
flatColors.forEach(([name, value]) => dart.push(`  static const Color ${name} = ${color(value, 'dart')};`));
dart.push('}', '', 'class KauiSpacing {');
Object.entries(source.spacing).forEach(([k, v]) => dart.push(`  static const double s${k} = ${px(v)};`));
dart.push('}', '', 'class KauiRadius {');
Object.entries(source.radius).forEach(([k, v]) => dart.push(`  static const double ${k} = ${px(v)};`));
dart.push('}', '');
fs.writeFileSync(path.join(out, 'kaui.tokens.dart'), dart.join('\n'));

const kotlin = ['// Generated by KAUI Token Builder.', 'package com.kaui.tokens', '', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.Dp', '', 'object KauiColors {'];
flatColors.forEach(([name, value]) => kotlin.push(`    val ${name} = ${color(value, 'kotlin')}`));
kotlin.push('}', '', 'object KauiSpacing {');
Object.entries(source.spacing).forEach(([k, v]) => kotlin.push(`    val s${k}: Dp = ${px(v)}.dp`));
kotlin.push('}', '', 'object KauiRadius {');
Object.entries(source.radius).forEach(([k, v]) => kotlin.push(`    val ${k}: Dp = ${px(v)}.dp`));
kotlin.push('}', '');
fs.writeFileSync(path.join(out, 'KauiTokens.kt'), kotlin.join('\n'));
const swift = ['// Generated by KAUI Token Builder.', 'import SwiftUI', '', 'public enum KauiColors {'];
flatColors.forEach(([name, value]) => swift.push(`    public static let ${name} = ${color(value, 'swift')}`));
swift.push('}', '', 'public enum KauiSpacing {');
Object.entries(source.spacing).forEach(([k, v]) => swift.push(`    public static let s${k}: CGFloat = ${px(v)}`));
swift.push('}', '', 'public enum KauiRadius {');
Object.entries(source.radius).forEach(([k, v]) => swift.push(`    public static let ${k}: CGFloat = ${px(v)}`));
swift.push('}', '');
fs.writeFileSync(path.join(out, 'KauiTokens.swift'), swift.join('\n'));
console.log('[tokens:build] Generated CSS, Dart, Kotlin, and Swift outputs.');

